document.getElementById('reflectionForm').addEventListener('submit', (event) => {
  event.preventDefault();
  const form = new FormData(event.currentTarget);
  const enjoyment = form.get('enjoyment');
  const likedMost = form.get('likedMost')?.toString().trim();
  const difficulty = form.get('difficulty')?.toString().trim();
  const tryAgain = form.get('tryAgain');

  const record = {
    id: state.currentExperience?.id,
    title: state.currentExperience?.titleEn || state.currentExperience?.titleAr,
    category: state.currentExperience?.category,
    enjoyment,
    likedMost,
    difficulty,
    tryAgain,
    timestamp: Date.now()
  };

  saveDiscoveryRecord(record);
  event.currentTarget.reset();
  closeModal(elements.reflectionModal);
  state.currentExperience = null;
});

